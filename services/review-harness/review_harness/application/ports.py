from typing import Protocol

from review_harness.domain.model import Failure, Run


class RunStorePort(Protocol):
    async def isolate_run(self, run_id: str) -> None: ...
    async def create_run(self, payload: dict) -> tuple[Run, bool]: ...
    async def get_run(self, run_id: str) -> Run: ...
    async def start_run(self, run_id: str) -> tuple[Run, bool]: ...
    async def fail_before_start(
        self, run_id: str, failure: Failure
    ) -> tuple[Run, bool]: ...
    async def cancel_pending(self, run_id: str) -> tuple[Run, bool]: ...
    async def request_cancel(self, run_id: str) -> tuple[Run, bool]: ...
    async def complete_success(
        self, run_id: str, review_package=None
    ) -> tuple[Run, bool]: ...
    async def complete_failure_safe(
        self, run_id: str, failure: Failure, recovery_code: str | None = None
    ) -> tuple[Run, bool]: ...
    async def complete_cancel(
        self, run_id: str, recovery_code: str | None = None
    ) -> tuple[Run, bool]: ...
    async def fail_cleanup_uncertain(
        self, run_id: str, failure: Failure
    ) -> tuple[Run, bool]: ...
    async def get_result(self, run_id: str) -> tuple[bytes, str]: ...
    async def read_events(self, run_id: str, after: int, limit: int) -> list[dict]: ...


class SchedulerPort(Protocol):
    accepting: bool

    def ensure_submitted(self, run_id: str) -> bool: ...
    def signal_cancel(self, run_id: str) -> None: ...
